/**
 * ColdMC's prison mines (the owner, 2026-11-24). mines.yml is generated by gen_prison.py; overrides.yml
 * holds cubes re-marked in game and always wins. Every WorldEdit job runs off the main thread.
 */
public final class Prison extends JavaPlugin implements Listener {
    final Map<String, Mine> mines = new LinkedHashMap<>();
    final Map<String, Double> extraExp = new HashMap<>();
    final Map<String, Double> nexoExp = new HashMap<>();
    String worldName = "world_prison";
    Builder builder;
    final Random rnd = new Random();
    final AtomicBoolean busy = new AtomicBoolean();
    final AtomicBoolean cancel = new AtomicBoolean();
    long tick;

    @Override
    public void onEnable() {
        saveDefaultConfig();
        builder = new Builder(this);
        load();
        getServer().getPluginManager().registerEvents(this, this);
        // one heartbeat per second: resets, mob waves, boss checks
        Bukkit.getScheduler().runTaskTimer(this, this::heartbeat, 100L, 20L);
    }

    @Override
    public void onDisable() {
        for (Mine m : mines.values()) despawn(m);
    }

    void load() {
        reloadConfig();
        mines.clear();
        extraExp.clear();
        nexoExp.clear();
        File f = new File(getDataFolder(), "mines.yml");
        if (!f.exists()) {
            getLogger().warning("no mines.yml - run knowledge/runtime/scripts/gen_prison.py --apply");
            return;
        }
        YamlConfiguration y = YamlConfiguration.loadConfiguration(f);
        worldName = y.getString("world", worldName);
        ConfigurationSection s = y.getConfigurationSection("mines");
        if (s != null) for (String id : s.getKeys(false)) mines.put(id, new Mine(id, s.getConfigurationSection(id)));
        ConfigurationSection ee = y.getConfigurationSection("extra-exp");
        if (ee != null) for (String k : ee.getKeys(false)) extraExp.put(k.toUpperCase(), ee.getDouble(k));
        ConfigurationSection ne = getConfig().getConfigurationSection("nexo-exp");
        if (ne != null) for (String k : ne.getKeys(false)) nexoExp.put(k, ne.getDouble(k));
        YamlConfiguration o = YamlConfiguration.loadConfiguration(new File(getDataFolder(), "overrides.yml"));
        for (String id : o.getKeys(false)) {
            Mine m = mines.get(id);
            if (m == null) continue;
            m.cubeMin = Mine.ints(o.getIntegerList(id + ".cube.min"));
            m.cubeMax = Mine.ints(o.getIntegerList(id + ".cube.max"));
        }
        long now = System.currentTimeMillis();
        for (Mine m : mines.values()) {
            m.lastReset = now;
            m.lastBoss = now;
        }
        getLogger().info(mines.size() + " prison mines in " + worldName);
    }

    World world() {
        return Bukkit.getWorld(worldName);
    }

    String msg(String key, String... kv) {
        String s = getConfig().getString("messages." + key, key);
        for (int i = 0; i + 1 < kv.length; i += 2) s = s.replace(kv[i], kv[i + 1]);
        return ChatColor.translateAlternateColorCodes('&', getConfig().getString("messages.prefix", "") + s);
    }

    // ------------------------------------------------------------------ WorldEdit jobs (async)
    void async(CommandSender who, String what, List<Mine> list, Job job) {
        World w = world();
        if (w == null) {
            who.sendMessage("§cWorld " + worldName + " is not loaded.");
            return;
        }
        if (!busy.compareAndSet(false, true)) {
            who.sendMessage("§cA prison job is already running.");
            return;
        }
        Bukkit.getScheduler().runTaskAsynchronously(this, () -> {
            int ok = 0;
            long t0 = System.currentTimeMillis();
            try {
                cancel.set(false);
                for (Mine m : list) {
                    if (cancel.get()) {
                        getLogger().info(what + " cancelled before " + m.id);
                        break;
                    }
                    try {
                        job.run(w, m);
                        ok++;
                        if (list.size() > 1) getLogger().info(what + " " + m.id + " (" + ok + "/" + list.size() + ")");
                    } catch (Exception e) {
                        getLogger().warning(what + " " + m.id + " failed: " + e);
                    }
                }
            } finally {
                busy.set(false);
            }
            int done = ok;
            long secs = (System.currentTimeMillis() - t0) / 1000;
            Bukkit.getScheduler().runTask(this, () -> who.sendMessage("§a" + what + ": " + done + "/" + list.size() + " in " + secs + " s"));
        });
    }

    interface Job {
        void run(World w, Mine m) throws Exception;
    }

    /** Refill one cube: lift anyone standing in it first (main thread), then the fill (async). */
    void reset(Mine m, boolean announce) {
        World w = world();
        if (w == null || busy.get()) return;
        for (Player p : w.getPlayers()) {
            Location l = p.getLocation();
            if (m.inCube(l) || m.inCube(l.clone().add(0, 1, 0))) {
                p.teleport(m.spawnAt(w));
                p.sendMessage(msg("lifted"));
            }
        }
        m.broken = 0;
        m.lastReset = System.currentTimeMillis();
        m.resets++;
        boolean occupied = !m.players(w).isEmpty();
        Bukkit.getScheduler().runTaskAsynchronously(this, () -> {
            try {
                builder.fill(w, m);
            } catch (Exception e) {
                getLogger().warning("reset " + m.id + " failed: " + e);
            }
        });
        if (announce) for (Player p : m.players(w)) p.sendMessage(msg("reset", "%mine%", m.title()));
        int every = getConfig().getInt("boss-every-resets", 12);
        if (occupied && every > 0 && m.resets % every == 0 && !bossAlive(m)) spawnBoss(m);
    }

    // ------------------------------------------------------------------ heartbeat
    void heartbeat() {
        World w = world();
        if (w == null || mines.isEmpty()) return;
        tick++;
        long now = System.currentTimeMillis();
        long resetMs = getConfig().getLong("reset-minutes", 10) * 60000L;
        double pct = getConfig().getDouble("reset-percent", 70) / 100.0;
        int spawnEvery = Math.max(5, getConfig().getInt("spawn-seconds", 30));
        int bossEvery = Math.max(1, getConfig().getInt("boss-check-minutes", 5)) * 60;
        for (Mine m : mines.values()) {
            List<Player> here = m.players(w);
            if (m.broken >= pct * m.cubeVolume() || (now - m.lastReset >= resetMs && !here.isEmpty())) {
                reset(m, true);
            } else if (now - m.lastReset >= resetMs) {
                m.lastReset = now;          // nobody there: no need to refill an untouched cube
                if (m.broken > 0) reset(m, false);
            }
            if (here.isEmpty()) {
                if (m.emptySince < 0) m.emptySince = now;
                else if (now - m.emptySince > getConfig().getLong("despawn-after-seconds", 120) * 1000L) despawn(m);
                continue;
            }
            m.emptySince = -1;
            if (tick % spawnEvery == m.index % spawnEvery) wave(w, m, here);
            if (tick % bossEvery == m.index % bossEvery) bossCheck(m, now);
        }
    }

    void despawn(Mine m) {
        for (UUID u : m.alive) {
            Entity e = Bukkit.getEntity(u);
            if (e != null) e.remove();
        }
        m.alive.clear();
        if (m.boss != null) {
            Entity e = Bukkit.getEntity(m.boss);
            if (e != null) e.remove();
            m.boss = null;
        }
    }

    void wave(World w, Mine m, List<Player> here) {
        m.alive.removeIf(u -> {
            Entity e = Bukkit.getEntity(u);
            return e == null || e.isDead() || !e.isValid();
        });
        int cap = getConfig().getInt("max-mobs", 4) + getConfig().getInt("mobs-per-player", 2) * here.size();
        int n = Math.min(getConfig().getInt("mobs-per-wave", 2), cap - m.alive.size());
        boolean elite = !m.elite.isEmpty() && rnd.nextDouble() < getConfig().getDouble("elite-chance", 0.04);
        if (elite) n = 1;
        for (int i = 0; i < n; i++) {
            Location at = spot(w, m, here.get(rnd.nextInt(here.size())).getLocation());
            if (at == null) continue;
            String kind = elite ? m.elite : m.mobs.isEmpty() ? null : m.mobs.get(rnd.nextInt(m.mobs.size()));
            Entity e = spawn(kind, at);
            if (e != null) {
                m.alive.add(e.getUniqueId());
                if (elite) for (Player p : here) p.sendMessage(msg("elite"));
            }
        }
    }

    Entity spawn(String kind, Location at) {
        if (kind == null) return null;
        Entity e = null;
        if (kind.startsWith("mythic:")) e = Hooks.mythic(kind.substring(7), at);
        else {
            try {
                e = at.getWorld().spawnEntity(at, EntityType.valueOf(kind.replace("vanilla:", "").toUpperCase()));
            } catch (IllegalArgumentException ignored) {
            }
        }
        if (e != null) e.setPersistent(false);
        return e;
    }

    /** A free spot 6-14 blocks from the player, inside the box, outside the cube, on solid ground. */
    Location spot(World w, Mine m, Location near) {
        for (int t = 0; t < 12; t++) {
            double a = rnd.nextDouble() * Math.PI * 2, d = 6 + rnd.nextDouble() * 8;
            int x = near.getBlockX() + (int) Math.round(Math.cos(a) * d), z = near.getBlockZ() + (int) Math.round(Math.sin(a) * d);
            for (int y = near.getBlockY() + 4; y >= near.getBlockY() - 6; y--) {
                Block feet = w.getBlockAt(x, y, z);
                Block below = feet.getRelative(0, -1, 0);
                if (feet.isPassable() && feet.getRelative(0, 1, 0).isPassable() && !feet.isLiquid()
                        && below.getType().isSolid() && below.getType() != Material.BARRIER) {
                    Location l = feet.getLocation().add(0.5, 0, 0.5);
                    if (m.inBox(l) && !m.inCube(l)) return l;
                    break;
                }
            }
        }
        return null;
    }

    boolean bossAlive(Mine m) {
        if (m.boss == null) return false;
        Entity e = Bukkit.getEntity(m.boss);
        if (e == null || e.isDead()) {
            m.boss = null;
            return false;
        }
        return true;
    }

    void bossCheck(Mine m, long now) {
        if (bossAlive(m) || m.bosses.isEmpty()) return;
        if (now - m.lastBoss < getConfig().getLong("boss-cooldown-minutes", 45) * 60000L) return;
        if (rnd.nextDouble() < getConfig().getDouble("boss-chance", 0.10)) spawnBoss(m);
    }

    boolean spawnBoss(Mine m) {
        World w = world();
        if (w == null || m.bosses.isEmpty()) return false;
        String kind = m.bosses.get(rnd.nextInt(m.bosses.size()));
        Location at = new Location(w, (m.cubeMin[0] + m.cubeMax[0]) / 2.0 + 0.5, m.cubeMax[1] + 1,
                (m.cubeMin[2] + m.cubeMax[2]) / 2.0 + 0.5);
        Entity e = spawn(kind, at);
        if (e == null) {
            getLogger().warning(m.id + ": boss " + kind + " did not spawn");
            return false;
        }
        m.boss = e.getUniqueId();
        m.lastBoss = System.currentTimeMillis();
        String bossName = e.getCustomName() != null ? e.getCustomName() : kind.replaceAll("^[a-z]+:", "");
        for (Player p : m.players(w)) {
            p.sendMessage(msg("boss", "%mine%", m.title()));
            p.sendTitle(ChatColor.translateAlternateColorCodes('&', getConfig().getString("messages.boss-title", "&4%boss%")
                    .replace("%boss%", ChatColor.stripColor(bossName))), m.title(), 10, 60, 20);
        }
        return true;
    }

    // ------------------------------------------------------------------ mining
    @EventHandler(priority = EventPriority.MONITOR)
    public void onBreak(BlockBreakEvent ev) {
        Block b = ev.getBlock();
        if (!b.getWorld().getName().equals(worldName)) return;
        Mine m = null;
        for (Mine x : mines.values()) if (x.inCube(b.getLocation())) {
            m = x;
            break;
        }
        if (m == null) return;
        Mine mine = m;
        String nexo = Hooks.nexoId(b);
        String type = b.getType().name();
        Player p = ev.getPlayer();
        // Nexo cancels and handles its own blocks, so read the result a tick later
        Bukkit.getScheduler().runTask(this, () -> {
            if (!b.getType().isAir()) return;
            mine.broken++;
            if (nexo != null) Hooks.miningExp(p, nexoExp.getOrDefault(nexo, 0.0), b.getLocation());
            else Hooks.miningExp(p, extraExp.getOrDefault(type, 0.0), b.getLocation());
        });
    }

    // ------------------------------------------------------------------ commands
    @Override
    public boolean onCommand(CommandSender s, Command c, String label, String[] a) {
        String sub = a.length > 0 ? a[0].toLowerCase() : "help";
        switch (sub) {
            case "cancel" -> {
                cancel.set(true);
                s.sendMessage(busy.get() ? "§eThe running job stops after the prison it is on." : "§7No job is running.");
            }
            case "reload" -> {
                load();
                s.sendMessage("§aPrison reloaded: " + mines.size() + " mines.");
            }
            case "list" -> {
                StringBuilder sb = new StringBuilder("§7");
                for (Mine m : mines.values()) sb.append(m.id).append(" ").append(m.symbol).append("  ");
                s.sendMessage(sb.toString());
            }
            case "info" -> {
                Mine m = mine(s, a);
                if (m == null) return true;
                s.sendMessage("§e" + m.title() + " §7(" + m.theme + ") new: §f" + m.newMaterial
                        + " §7cube " + str(m.cubeMin) + " -> " + str(m.cubeMax) + " §7mined " + m.broken + "/" + m.cubeVolume()
                        + " §7mobs " + m.alive.size() + " boss " + (bossAlive(m) ? "yes" : "no"));
            }
            case "build" -> {
                List<Mine> list = pick(s, a);
                if (list == null) return true;
                boolean paste = !(a[a.length - 1].equalsIgnoreCase("nopaste"));
                s.sendMessage("§7Building " + list.size() + " prison(s)" + (paste ? "" : " without pasting") + "...");
                async(s, "build", list, (w, m) -> builder.build(w, m, paste));
            }
            case "reset" -> {
                List<Mine> list = pick(s, a);
                if (list == null) return true;
                for (Mine m : list) reset(m, true);
                s.sendMessage("§aReset " + list.size() + " cube(s).");
            }
            case "tp" -> {
                Mine m = mine(s, a);
                if (m == null || !(s instanceof Player p) || world() == null) return true;
                p.teleport(m.spawnAt(world()));
            }
            case "boss" -> {
                Mine m = mine(s, a);
                if (m == null) return true;
                s.sendMessage(spawnBoss(m) ? "§aBoss spawned in " + m.title() : "§cNo boss spawned.");
            }
            case "setcube" -> {
                Mine m = mine(s, a);
                if (m == null || !(s instanceof Player p)) return true;
                int[][] sel = selection(p);
                if (sel == null) {
                    s.sendMessage("§cMake a WorldEdit selection of the cube first (//wand).");
                    return true;
                }
                m.cubeMin = sel[0];
                m.cubeMax = sel[1];
                File f = new File(getDataFolder(), "overrides.yml");
                YamlConfiguration o = YamlConfiguration.loadConfiguration(f);
                o.set(m.id + ".cube.min", List.of(sel[0][0], sel[0][1], sel[0][2]));
                o.set(m.id + ".cube.max", List.of(sel[1][0], sel[1][1], sel[1][2]));
                try {
                    o.save(f);
                } catch (Exception e) {
                    s.sendMessage("§cCould not save overrides.yml: " + e);
                }
                p.performCommand("rg redefine -w " + worldName + " prison_" + m.id);
                s.sendMessage("§aCube of " + m.title() + " set to " + str(sel[0]) + " -> " + str(sel[1]) + ". Run /prison build " + m.id + " nopaste to fill it.");
            }
            default -> s.sendMessage("§e/prison list | info <id> | tp <id> | build <id|all|from <id>> [nopaste] | reset <id|all> | boss <id> | setcube <id> | cancel | reload");
        }
        return true;
    }

    int[][] selection(Player p) {
        try {
            var actor = com.sk89q.worldedit.bukkit.BukkitAdapter.adapt(p);
            var r = com.sk89q.worldedit.WorldEdit.getInstance().getSessionManager().get(actor)
                    .getSelection(com.sk89q.worldedit.bukkit.BukkitAdapter.adapt(p.getWorld()));
            var a = r.getMinimumPoint();
            var b = r.getMaximumPoint();
            return new int[][]{{a.x(), a.y(), a.z()}, {b.x(), b.y(), b.z()}};
        } catch (Exception e) {
            return null;
        }
    }

    static String str(int[] v) {
        return v[0] + "," + v[1] + "," + v[2];
    }

    Mine mine(CommandSender s, String[] a) {
        Mine m = a.length > 1 ? mines.get(a[1].toLowerCase()) : null;
        if (m == null) s.sendMessage("§cUnknown prison. /prison list");
        return m;
    }

    List<Mine> pick(CommandSender s, String[] a) {
        if (a.length > 1 && a[1].equalsIgnoreCase("all")) return new ArrayList<>(mines.values());
        if (a.length > 2 && a[1].equalsIgnoreCase("from")) {     // resume a long build: this prison and every one after it
            List<Mine> l = new ArrayList<>();
            boolean on = false;
            for (Mine m : mines.values()) {
                if (m.id.equalsIgnoreCase(a[2])) on = true;
                if (on) l.add(m);
            }
            if (l.isEmpty()) s.sendMessage("§cUnknown prison. /prison list");
            return l.isEmpty() ? null : l;
        }
        Mine m = mine(s, a);
        return m == null ? null : List.of(m);
    }

    @Override
    public List<String> onTabComplete(CommandSender s, Command c, String label, String[] a) {
        if (a.length == 1) return List.of("list", "info", "tp", "build", "reset", "boss", "setcube", "cancel", "reload");
        if (a.length == 2) {
            List<String> l = new ArrayList<>();
            if (a[0].equalsIgnoreCase("build") || a[0].equalsIgnoreCase("reset")) l.add("all");
            for (String id : mines.keySet()) if (id.startsWith(a[1].toLowerCase())) l.add(id);
            return l;
        }
        return List.of();
    }

    static boolean living(Entity e) {
        return e instanceof LivingEntity;
    }
}
